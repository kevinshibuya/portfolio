/**
 * The stream — the archive's accessible twin — as the acceptance for pipeline 3.
 *
 * **Corrected 2026-09-10.** The plan has this spec consume `archive` and
 * `yearBlocks` from `src/data/archive`. It cannot: that module reaches
 * `embeds.csv?raw` through `embeds.ts`, a Vite-only import Playwright's loader
 * will not follow — the fixture's own docstring says so. Everything the plan
 * wanted from `archive` comes from `frieze-cells.json` instead (one cell per
 * item, regenerated by a unit test that fails on drift) and from the DOM:
 * `extent.blocks` IS `yearBlocks` (year and count, newest first), and
 * `cells.length` is `archive.length`. `playheadForItem(id, layout, extent)` is
 * `playheadForColumn(cell.col + cell.span / 2, extent)` by definition, so the
 * fixture cell stands in for the layout too.
 */

const fixture = JSON.parse(
  readFileSync('tests/e2e/fixtures/frieze-cells.json', 'utf8'),
) as FriezeFixture
const extent = fixture.extent
const ROWS = fixture.cells.length
const cellOf = (itemId: string) => fixture.cells.find((c) => c.itemId === itemId)!

/**
 * The row index that OPENS each year block, from the fixture's own counts.
 *
 * These are the rows whose focus is guaranteed to travel. Focus is gated on the
 * year block (assumption 27): a row inside the block already in frame is one
 * the reader can see, so it does not move the camera. Only a row that crosses a
 * boundary does — which makes a block's first row the one place the applied
 * position must equal that row's own cell target.
 */
const BLOCK_STARTS = extent.blocks.reduce<number[]>(
  (acc, b, i) => (i === 0 ? [0] : [...acc, acc[i - 1] + extent.blocks[i - 1].count]),
  [],
)

interface Metrics {
  columns: number
  wrapperTop: number
  wrapperHeight: number
  innerHeight: number
}

async function metrics(page: Page): Promise<Metrics> {
  const columns = columnsFromSvh(await readSvh(page))!
  expect(columns, 'data-svh must resolve to a whole column count').toBeGreaterThan(0)
  const box = await page.evaluate(() => {
    const w = document.querySelector('#projects .scene-scroll') as HTMLElement
    return {
      wrapperTop: w.getBoundingClientRect().top + window.scrollY,
      wrapperHeight: w.offsetHeight,
      innerHeight: window.innerHeight,
    }
  })
  return { columns, ...box }
}

/** Where the page must end up when `itemId` takes focus. */
function targetFor(itemId: string, m: Metrics): number {
  const cell = cellOf(itemId)
  const playhead = playheadForColumn(cell.col + cell.span / 2, extent)
  return scrollTargetFor(playhead, m.wrapperTop, m.wrapperHeight, m.innerHeight, m.columns)
}

/** The stream's rows in DOM order, which is the wall's reading order. */
const rowIds = (page: Page): Promise<string[]> =>
  page.$$eval('#archive li.stream-item', (els) =>
    els.map((el) => (el as HTMLElement).dataset.itemId!),
  )

const FOCUSABLE =
  'a[href], button:not([disabled]), input:not([disabled]), select:not([disabled]), textarea:not([disabled]), [tabindex]:not([tabindex="-1"])'

/**
 * Focus the element immediately before the stream in DOCUMENT order, so the
 * next Tab enters it. Found rather than named: the stream is the first child of
 * `#projects`, and what precedes it is whatever the hero happens to end with.
 */
async function tabToStreamEdge(page: Page): Promise<void> {
  const ok = await page.evaluate((sel) => {
    const all = Array.from(document.querySelectorAll<HTMLElement>(sel)).filter(
      (el) => el.offsetParent !== null || getComputedStyle(el).position === 'fixed',
    )
    const first = all.findIndex((el) => el.closest('#archive'))
    if (first <= 0) return false
    all[first - 1].focus()
    return document.activeElement === all[first - 1]
  }, FOCUSABLE)
  expect(ok, 'could not find the focusable immediately before the stream').toBe(true)
}

/**
 * Reach a row with REAL Tab presses. `:focus-visible` is what turns a row into
 * the pill, and a scripted `.focus()` does not reliably match it, so a
 * `.focus()`-driven test can pass on a pill nobody can see.
 */
async function tabToRow(page: Page, index: number): Promise<string> {
  await tabToStreamEdge(page)
  // One Tab into the skip link, then one per row.
  for (let i = 0; i <= index + 1; i++) await page.keyboard.press('Tab')
  const id = await page.evaluate(
    () => (document.activeElement?.closest('li.stream-item') as HTMLElement | null)?.dataset.itemId ?? null,
  )
  expect(id, `Tab did not land on row ${index}`).toBe((await rowIds(page))[index])
  return id!
}

/** The focused element's pill geometry. */
const pillBox = (page: Page) =>
  page.evaluate(() => {
    const el = document.activeElement as HTMLElement
    const r = el.getBoundingClientRect()
    const cs = getComputedStyle(el)
    return { top: r.top, left: r.left, width: r.width, clipPath: cs.clipPath, position: cs.position }
  })

async function settledScrollY(page: Page, timeout = 4000): Promise<number> {
  return page.evaluate(
    (ms) =>
      new Promise<number>((resolve) => {
        let last = window.scrollY
        let still = 0
        const t0 = performance.now()
        const tick = (): void => {
          if (window.scrollY === last) still++
          else {
            still = 0
            last = window.scrollY
          }
          if (still >= 10 || performance.now() - t0 > ms) resolve(window.scrollY)
          else requestAnimationFrame(tick)
        }
        requestAnimationFrame(tick)
      }),
    timeout,
  )
}

