    await page.waitForTimeout(900)
    expect(await page.locator('#archive :focus-visible').count()).toBe(0)
    // The page DOES move here, and should: focus landed on a real element far
    // up the document and the browser scrolled to it. What must not happen is a
    // camera travel — so the movement is the browser's, and the proof is that
    // the newly focused element is the thing now in view.
